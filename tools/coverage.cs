// Coverage matrix of the curated clients against Cloudflare's OpenAPI schema (0.9.0).
//
//   dotnet run tools/coverage.cs               write openapi/COVERAGE.md (runs CoverageReportTests in write mode)
//   dotnet run tools/coverage.cs -- --check    fail when openapi/COVERAGE.md is stale (the same test without write mode, as in CI)
//   dotnet run tools/coverage.cs -- --index    rewrite openapi/operations.tsv from the schema pinned in openapi/cloudflare-openapi.lock.json
//                                              (download cached in openapi/cache, SHA-256 verified; tools/generate.cs calls this after Kiota)
//
// How the matrix is built: the test project calls every public method of every curated client (reflection, sample arguments, fake HTTP handler, no
// network) with AllowWrites = true and records method + path of each request; each request is matched against openapi/operations.tsv. A schema operation
// counts as "curated" when at least one curated method sends it. Product areas and priorities are defined in tests/…/Coverage/CoverageMatrix.cs.

using System.Diagnostics;
using System.Net.Http.Headers;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json.Nodes;

var root = FindRoot(Directory.GetCurrentDirectory());
if (args.Contains("--index")) return await WriteIndexAsync(root);

var tests = Path.Combine(root, "tests", "InfinitySuite360.Cloudflare.Tests");
var psi = new ProcessStartInfo("dotnet", ["test", tests, "--filter", "FullyQualifiedName~CoverageReportTests", "--nologo"]) { WorkingDirectory = root };
if (!args.Contains("--check")) psi.Environment["CLOUDFLARE_COVERAGE_WRITE"] = "1";
using var process = Process.Start(psi)!;
await process.WaitForExitAsync();
Console.WriteLine(process.ExitCode == 0
    ? args.Contains("--check") ? "openapi/COVERAGE.md is current." : "openapi/COVERAGE.md written."
    : "Coverage run failed (see the test output above).");
return process.ExitCode;

static async Task<int> WriteIndexAsync(string root)
{
    var lockPath = Path.Combine(root, "openapi", "cloudflare-openapi.lock.json");
    var lockDoc = JsonNode.Parse(await File.ReadAllTextAsync(lockPath))!.AsObject();
    var repository = (string)lockDoc["repository"]!;
    var file = (string)lockDoc["file"]!;
    var sha = (string)lockDoc["commit"]!;
    var expected = (string?)lockDoc["sha256"] ?? throw new InvalidOperationException("The lock file has no SHA-256; run tools/generate.cs first.");
    var cacheDir = Path.Combine(root, "openapi", "cache");
    Directory.CreateDirectory(cacheDir);
    var specPath = Path.Combine(cacheDir, $"openapi-{sha[..12]}.json");
    if (!File.Exists(specPath))
    {
        using var http = new HttpClient();
        http.DefaultRequestHeaders.UserAgent.Add(new ProductInfoHeaderValue("InfinitySuite360-Cloudflare-Coverage", "1.0"));
        var url = $"https://raw.githubusercontent.com/{repository}/{sha}/{file}";
        Console.WriteLine($"Downloading {url}");
        await File.WriteAllBytesAsync(specPath, await http.GetByteArrayAsync(url));
    }
    var hash = Convert.ToHexString(SHA256.HashData(await File.ReadAllBytesAsync(specPath))).ToLowerInvariant();
    if (hash != expected)
    {
        File.Delete(specPath);
        throw new InvalidOperationException($"SHA-256 mismatch for {file}@{sha}: expected {expected}, got {hash}.");
    }

    var doc = JsonNode.Parse(await File.ReadAllTextAsync(specPath))!.AsObject();
    string[] methods = ["get", "post", "put", "patch", "delete"];
    var ops = doc["paths"]!.AsObject()
        .SelectMany(p => p.Value!.AsObject().Where(m => methods.Contains(m.Key)).Select(m => (Method: m.Key.ToUpperInvariant(), Path: p.Key)))
        .OrderBy(o => o.Path, StringComparer.Ordinal).ThenBy(o => o.Method, StringComparer.Ordinal)
        .ToList();
    var sb = new StringBuilder();
    sb.Append($"# Operations of {repository}@{sha} ({lockDoc["committedAt"]}), file {file}, SHA-256 {hash}.\n");
    sb.Append("# Generated by tools/coverage.cs --index; do not edit. Columns: method, path template.\n");
    foreach (var (m, p) in ops) sb.Append(m).Append('\t').Append(p).Append('\n');
    await File.WriteAllTextAsync(Path.Combine(root, "openapi", "operations.tsv"), sb.ToString(), new UTF8Encoding(false));
    Console.WriteLine($"openapi/operations.tsv: {ops.Count} operations.");
    return 0;
}

static string FindRoot(string start)
{
    for (var dir = new DirectoryInfo(start); dir is not null; dir = dir.Parent)
        if (File.Exists(Path.Combine(dir.FullName, "InfinitySuite360.Cloudflare.sln"))) return dir.FullName;
    throw new InvalidOperationException("Run from inside the repository (InfinitySuite360.Cloudflare.sln not found).");
}
